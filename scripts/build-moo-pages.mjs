#!/usr/bin/env node
// Bundles the MOO-598 ticket pages into self-contained HTML files — config,
// styles, the SDK and the page logic inlined, nothing else to host — for
// embedding in BTS or any static host:
//
//   dist/moo/facilities.html   Building Facilities and Supplies Request
//   dist/moo/it.html           Onsite Headquarters IT Incident
//
//   npm run build:pages                        # config: pages/moo/config.local.js
//   npm run build:pages -- --config other.js   # another config file
//   npm run build:pages -- --dry-run           # Continue only shows the URL
//
// Deployed copies always navigate on Continue (dryRun forced false) unless
// --dry-run. The output carries the Jibestream client secret from the config:
// dist/ is gitignored — never commit it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const optValue = (name) => {
	const i = args.indexOf(name);
	return i === -1 ? null : args[i + 1];
};
const dryRun = args.includes('--dry-run');
const pagesDir = path.join(root, 'pages/moo');
const outDir = path.join(root, 'dist/moo');

function read(file, hint) {
	if (!fs.existsSync(file)) {
		console.error(`Missing ${path.relative(root, file)} — ${hint}`);
		process.exit(1);
	}
	return fs.readFileSync(file, 'utf8');
}

const config = read(
	path.resolve(optValue('--config') ?? path.join(pagesDir, 'config.local.js')),
	'copy pages/moo/config.example.js to pages/moo/config.local.js and fill it in.',
);
const sdk = read(path.join(root, 'dist/map-sdk.iife.js'), 'run `npm run build` first.');
const css = read(path.join(pagesDir, 'ticket-page.css'), 'page styles.');
const logic = read(path.join(pagesDir, 'ticket-page.js'), 'page logic.');

// `</script` inside inlined code would close the tag early.
const script = (code) => `<script>\n${code.replace(/<\/script/gi, '<\\/script')}\n</script>`;

// Each tag must appear exactly once; split/join (not String.replace) so `$`
// sequences in the inlined code are never read as replacement patterns.
function inline(html, tag, replacement, page) {
	const parts = html.split(tag);
	if (parts.length !== 2) {
		console.error(`${page}: expected one \`${tag}\`, found ${parts.length - 1}.`);
		process.exit(1);
	}
	return parts.join(replacement);
}

fs.mkdirSync(outDir, { recursive: true });
for (const page of ['facilities.html', 'it.html']) {
	let html = read(path.join(pagesDir, page), 'page markup.');
	// The source's header comment describes the separate files; say what this is instead.
	html = html.replace(
		/^<!doctype html>\s*<!--[\s\S]*?-->/i,
		`<!doctype html>\n<!-- MOO-598 ticket location picker, self-contained build (${dryRun ? 'DRY RUN' : 'live'}).\n     Generated by scripts/build-moo-pages.mjs from pages/moo/ — edit those, not this file.\n     Contains the Jibestream client credentials: host it only where the page is meant to run. -->`,
	);
	html = inline(html, '<link rel="stylesheet" href="./ticket-page.css" />', `<style>\n${css}\n</style>`, page);
	html = inline(html, '<script src="./config.local.js"></script>',
		script(`${config}\nwindow.MOO_TICKET_CONFIG.dryRun = ${dryRun};`), page);
	html = inline(html, '<script src="../../dist/map-sdk.iife.js"></script>', script(sdk), page);
	html = inline(html, '<script src="./ticket-page.js"></script>', script(logic), page);
	const out = path.join(outDir, page);
	fs.writeFileSync(out, html);
	console.log(`${path.relative(root, out)}  ${(Buffer.byteLength(html) / 1024).toFixed(0)} KB${dryRun ? '  (dry run)' : ''}`);
}
